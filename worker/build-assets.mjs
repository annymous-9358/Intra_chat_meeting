// Packs public/ into worker/assets.gen.mjs so the Worker serves the web app itself (no separate asset upload).
// Run automatically by `wrangler deploy` / `wrangler dev` (see [build] in wrangler.toml).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../public');
const TYPES = { html: 'text/html; charset=utf-8', css: 'text/css; charset=utf-8', js: 'text/javascript; charset=utf-8', svg: 'image/svg+xml',
  png: 'image/png', ico: 'image/x-icon', webmanifest: 'application/manifest+json', json: 'application/json', txt: 'text/plain; charset=utf-8' };
const out = {};
const walk = dir => {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) { walk(p); continue; }
    const ext = f.name.split('.').pop().toLowerCase();
    if (!TYPES[ext]) continue;                                   // LICENSE files etc. aren't served
    const buf = fs.readFileSync(p), url = '/' + path.relative(root, p).split(path.sep).join('/');
    out[url] = { type: TYPES[ext], etag: '"' + crypto.createHash('sha1').update(buf).digest('base64url').slice(0, 16) + '"', b64: buf.toString('base64') };
  }
};
walk(root);
fs.writeFileSync(new URL('./assets.gen.mjs', import.meta.url), '// generated by build-assets.mjs — do not edit\nexport default ' + JSON.stringify(out) + ';\n');
console.log(`packed ${Object.keys(out).length} files from public/`);
